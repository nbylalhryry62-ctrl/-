#!/usr/bin/env python3
"""Compile data/qbank_full_*.json into pwa-deploy/js/data/qbank-data.js.

The app reads the bank from this file (deflate-raw + base64, repeated strings interned).
Run it after any change to the bank, then run scripts/validate_bank.py.

Row layout: [id, faculty, track, subjectId, subjectName, unit, lesson, grade,
             difficulty, lang, source, status, question, options, correctIndex, explanation]
Fields 1-5 and 7-11 (except lesson, index 6) are indexes into the string table "m".
"""
import base64, glob, json, os, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
qs = json.load(open(glob.glob(os.path.join(ROOT, "data", "qbank_full_*.json"))[0], encoding="utf-8"))

table, index = [], {}
def intern(s):
    s = s or ""
    if s not in index:
        index[s] = len(table)
        table.append(s)
    return index[s]

rows = []
for q in qs:
    rows.append([
        q["id"], intern(q["facultyId"]), intern(q["trackId"]), intern(q["subjectId"]), intern(q["subjectName"]), intern(q["unit"]),
        q.get("lesson") or "", intern(q.get("gradeRef")), intern(q["difficulty"]), intern(q["lang"]), intern(q["sourceBank"]),
        intern(q["reviewStatus"]), q["question"], q["options"], q["correctIndex"], q["explanation"],
    ])

payload = json.dumps({"m": table, "q": rows}, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
blob = base64.b64encode(zlib.compress(payload, 9)[2:-4]).decode()
out = os.path.join(ROOT, "pwa-deploy", "js", "data", "qbank-data.js")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/build_data.py. Do not edit by hand. */\n")
    f.write("window.Aden = window.Aden || {};\n")
    f.write(f'Aden.qbankB64 = "{blob}";\nAden.qbankCount = {len(rows)};\n')
print(f"wrote {out}: {len(rows)} questions, {len(blob) / 1e6:.2f} MB base64")
